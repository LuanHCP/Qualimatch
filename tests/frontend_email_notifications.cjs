const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
let reads=0;
const context=vm.createContext({esc:s=>String(s).replaceAll('<','&lt;'),api:()=>{reads++;}});
vm.runInContext(fs.readFileSync('frontend/static/email_notifications.js','utf8'),context);
assert.equal(reads,0,'Loading the script must not fetch preferences');
const html=context.emailPreferencesMarkup({email:'<unsafe>',can_subscribe_bv:false,smtp_configured:false,delivery_counts:{PENDING:2,FAILED:1}});
assert(html.includes('&lt;unsafe>'));
assert(html.includes('disabled'));
assert(html.includes('Envio ainda não configurado'));
assert(html.includes('Na fila: 2'));
assert(html.includes('Tentar enviar novamente (1)'));
const enabled=context.emailPreferencesMarkup({email:'test@example.invalid',can_subscribe_bv:true,smtp_configured:true,bv_new_certificates:true});
assert(enabled.includes('checked'));
assert(!enabled.match(/id="email-bv-enabled"[^>]*disabled/));
assert(enabled.includes('Notificações do Windows'));
assert(enabled.includes('Navegador ou endereço não compatível'));
console.log('Email preferences rendering and lazy-loading checks passed');
